"""Stage matching stock files and generate the recovery copy rules."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from huawei_container import STOCK_SHA256


def main():
    tree = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--blobs', type=Path, required=True)
    parser.add_argument('--recovery-ramdisk', type=Path, required=True)
    parser.add_argument('--magiskboot', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=tree)
    args = parser.parse_args()
    donor = args.recovery_ramdisk.read_bytes()
    if hashlib.sha256(donor).hexdigest() != STOCK_SHA256:
        parser.error('Recovery donor does not match EMUI 9.1.0.399.')
    host = args.magiskboot.read_bytes()
    if host[:6] != b'\x7fELF\x02\x01' or struct.unpack_from('<H', host, 18)[0] != 62:
        parser.error('MagiskBoot must be the Linux x86_64 ELF binary.')

    files = [line.strip() for line in (tree/'proprietary-files.txt').read_text().splitlines()
             if line.strip() and not line.startswith('#')]
    inputs = []
    for name in files:
        relative = Path(name)
        if relative.is_absolute() or '..' in relative.parts:
            raise ValueError('Invalid proprietary file path: '+name)
        source = args.blobs/relative
        if not source.is_file() and name.startswith('vendor/odm/'):
            source = args.blobs/name.removeprefix('vendor/')
        if not source.is_file():
            raise FileNotFoundError('Missing stock file: '+name)
        data = source.read_bytes()
        inputs.append((name, data))

    for manifest, makefile in [('crypto/runtime-files.txt', 'crypto-blobs.mk'),
                               ('crypto/wifi-files.txt', 'wifi-blobs.mk')]:
        bundled = []
        for line in (tree/manifest).read_text().splitlines():
            if not line.strip() or line.startswith('#'):
                continue
            name, expected = line.split()
            relative = Path(name)
            if relative.is_absolute() or '..' in relative.parts:
                raise ValueError('Invalid bundled firmware path: ' + name)
            data = (args.blobs/relative).read_bytes()
            if hashlib.sha256(data).hexdigest() != expected:
                raise ValueError('File differs from matching EMUI firmware: ' + name)
            target = args.output/'proprietary'/relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            target.chmod(0o755 if '/bin/' in name else 0o644)
            bundled.append(name)
        rules = ['# Generated by tools/setup-vendor.py. Huawei proprietary firmware.',
                 'PRODUCT_COPY_FILES += ' + chr(92)]
        for index, name in enumerate(bundled):
            suffix = ' ' + chr(92) if index + 1 < len(bundled) else ''
            rules.append('    $(DEVICE_PATH)/proprietary/' + name + ':recovery/root/' + name + suffix)
        (args.output/makefile).write_text('\n'.join(rules) + '\n')

    records = []
    for name, data in inputs:
        target = args.output/'proprietary'/name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        record = dict(path=name, source=name, size=len(data), sha256=hashlib.sha256(data).hexdigest())
        records.append(record)
    lines = ['# Generated by tools/setup-vendor.py. Huawei proprietary firmware.',
             'PRODUCT_COPY_FILES += \\']
    for index, name in enumerate(files):
        suffix = ' \\' if index + 1 < len(files) else ''
        lines.append('    $(DEVICE_PATH)/proprietary/'+name+':recovery/root/'+name+suffix)
    lines += ['', 'TARGET_RECOVERY_DEVICE_MODULES += libcutils libutils liblog libc++',
              'RECOVERY_LIBRARY_SOURCE_FILES += \\',
              '    $(TARGET_OUT_SHARED_LIBRARIES)/libcutils.so \\',
              '    $(TARGET_OUT_SHARED_LIBRARIES)/libutils.so \\',
              '    $(TARGET_OUT_SHARED_LIBRARIES)/liblog.so \\',
              '    $(TARGET_OUT_SHARED_LIBRARIES)/libc++.so']
    (args.output/'stock-blobs.mk').write_bytes(('\n'.join(lines)+'\n').encode())
    (args.output/'stock-blobs.json').write_bytes((json.dumps(dict(files=records), indent=2)+'\n').encode())
    prebuilt = args.output/'prebuilt'
    prebuilt.mkdir(exist_ok=True)
    (prebuilt/'empty-kernel').write_bytes(b'')
    (prebuilt/'stock-recovery_ramdisk.img').write_bytes(donor)
    (prebuilt/'host-magiskboot').write_bytes(host)
    (prebuilt/'host-magiskboot').chmod(0o755)
    (args.output/'proprietary/vendor/bin/aptouch_daemon').chmod(0o755)
    print('Prepared '+str(len(records))+' stock files and recovery build inputs.')


if __name__ == '__main__':
    main()
